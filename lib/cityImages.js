export function getCityImage(citySlug, type = "") {
    if (CITY_IMAGES[citySlug]) return CITY_IMAGES[citySlug];

    // Select a deterministic fallback from the pool based on the slug's hash
    const hash = citySlug.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
    const index = hash % FALLBACK_POOL.length;

    return FALLBACK_POOL[index];
}
